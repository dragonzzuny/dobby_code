"""Wire the dobby adapter into a checkout of kakao/OrchestrationBench.

The benchmark is a third-party repository under its own licence and it is not
vendored here. This installs into a checkout the operator already has, and it is
idempotent: running it twice leaves the same two edits.

    python evals/orchestration/install.py <path-to-OrchestrationBench>

What it does, and nothing else:

    copies   contract.py and dobby_model.py into <checkout>/src/models/
    patches  src/utils/model_factory.py to recognise provider "dobby"
    patches  config/base_config/multiagent_config.yaml with an `llms` entry per
             arm — `stepwise_scenario_processor.py` resolves `--model <name>`
             through `llms.<name>`, which is a different path from the
             `config/dobby_*.yaml` the `evaluate` wrapper reads. Both are
             written because both are real entry points and an operator who
             takes the direct one should not find half an installation.
    writes   config/dobby_*.yaml, one per arm

Why patch rather than fork: the two edits are small and named, so an operator can
read them, and a `git diff` in the checkout shows exactly what this repository
added to somebody else's benchmark. A fork would hide that in a merge base.
"""

from __future__ import annotations

import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DOBBY_ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))

FACTORY_IMPORT = "from src.models.dobby_model import DobbyModel"

FACTORY_DETECT = '''    if provider == "dobby":
        return "dobby"
'''

FACTORY_BRANCH = '''    if provider == "dobby":
        return DobbyModel(
            model_name=model_name,
            temperature=temperature,
            token_callback=token_callback,
            provider=llm_config.get("cli_provider", "claude"),
            arm=llm_config.get("arm", "solo"),
            cli_model=llm_config.get("cli_model"),
            timeout_s=int(llm_config.get("timeout_s", 600)),
        )

'''

#: One config per arm. The MODEL is pinned in every one of them, because codex
#: and agy do not report theirs and an arm whose tokens belong to no model
#: cannot be compared with one whose do.
ARMS = {
    "dobby_claude": ("claude", "solo", None),
    "dobby_codex": ("codex", "solo", "gpt-5.6-sol"),
    "dobby_agy": ("agy", "solo", "gemini-3.5-flash-high"),
    "dobby_fable": ("claude", "solo", "claude-fable-5"),
    "dobby_loop": ("claude", "dobby", None),
}

CONFIG = """# Generated by dobby's evals/orchestration/install.py — do not hand-edit.
# Arm: {alias}
#   cli_provider {cli_provider}
#   arm          {arm}
#   cli_model    {cli_model}
#
# `arm: solo` is one CLI call returned as-is. `arm: dobby` adds the contract
# loop: an answer the benchmark's own extractor cannot read is retried on a
# DIFFERENT provider. Only the arm differs between these files, which is what
# makes the harness the variable and the model the control.

defaults:
  - base_config/eval_config
  - _self_

model:
  provider: dobby
  model_alias: {alias}
  model: {alias}
  cli_provider: {cli_provider}
  arm: {arm}
  cli_model: {cli_model_yaml}
  temperature: 0.2
  timeout_s: 600

benchmark:
  temperature: 0.2
  num_iter: 1
  batch_size: 4
  max_retries: 2
"""


def patch_factory(path: str) -> str:
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    changed = []

    if FACTORY_IMPORT not in text:
        anchor = "from src.models import BedrockModel"
        if anchor not in text:
            raise SystemExit(f"{path}: import anchor not found; the benchmark "
                             f"has moved and this patch needs re-reading")
        text = text.replace(anchor, anchor + "\n" + FACTORY_IMPORT, 1)
        changed.append("import")

    if 'if provider == "dobby":\n        return "dobby"' not in text:
        anchor = '    if provider in ("gemini", "claude", "openai", "bedrock", "opensource"):'
        if anchor not in text:
            raise SystemExit(f"{path}: detect anchor not found")
        text = text.replace(anchor, FACTORY_DETECT + anchor, 1)
        changed.append("detect")

    if "return DobbyModel(" not in text:
        anchor = '    if provider == "gemini":'
        if anchor not in text:
            raise SystemExit(f"{path}: branch anchor not found")
        text = text.replace(anchor, FACTORY_BRANCH + anchor, 1)
        changed.append("branch")

    if changed:
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    return ", ".join(changed) or "already patched"


def patch_multiagent_config(path: str) -> str:
    """Add one `llms.<alias>` entry per arm, leaving the rest of the file alone.

    Edited as text rather than round-tripped through a YAML loader: the file
    holds the orchestrator prompt as a multi-line block scalar and a dump would
    reflow it. The prompt is the benchmark's control variable and reformatting
    it would change what every arm is asked.
    """
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    if "llms:" not in text:
        raise SystemExit(f"{path}: no `llms:` block; the benchmark has moved")

    block, added = "", 0
    for alias, (cli_provider, arm, cli_model) in sorted(ARMS.items()):
        if f"\n  {alias}:" in text:
            continue
        added += 1
        block += (f"  {alias}:\n"
                  f"    provider: dobby\n"
                  f"    model: {alias}\n"
                  f"    cli_provider: {cli_provider}\n"
                  f"    arm: {arm}\n"
                  f"    cli_model: "
                  f"{'null' if cli_model is None else cli_model}\n")
    if not block:
        return "already patched"

    text = text.replace("llms:\n", "llms:\n" + block, 1)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    # Counted, not derived from the line total: each arm emits six lines and a
    # `// 5` here reported five arms as six the first time it ran.
    return f"{added} arm(s) added"


def main(checkout: str) -> int:
    checkout = os.path.abspath(checkout)
    models = os.path.join(checkout, "src", "models")
    factory = os.path.join(checkout, "src", "utils", "model_factory.py")
    config = os.path.join(checkout, "config")
    for path in (models, factory, config):
        if not os.path.exists(path):
            raise SystemExit(f"{path} is missing; is {checkout} an "
                             f"OrchestrationBench checkout?")

    for name in ("contract.py", "dobby_model.py"):
        shutil.copy2(os.path.join(HERE, name), os.path.join(models, name))
        print(f"  copied  src/models/{name}")

    print(f"  patched src/utils/model_factory.py: {patch_factory(factory)}")

    multiagent = os.path.join(config, "base_config", "multiagent_config.yaml")
    if os.path.exists(multiagent):
        print(f"  patched config/base_config/multiagent_config.yaml: "
              f"{patch_multiagent_config(multiagent)}")

    for alias, (cli_provider, arm, cli_model) in sorted(ARMS.items()):
        path = os.path.join(config, f"{alias}.yaml")
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(CONFIG.format(
                alias=alias, cli_provider=cli_provider, arm=arm,
                cli_model=cli_model or "(provider reports its own)",
                cli_model_yaml=("null" if cli_model is None
                                else f'"{cli_model}"')))
        print(f"  wrote   config/{alias}.yaml")

    print()
    print("Run one arm with DOBBY_ROOT set so the adapter can import dobby:")
    print(f"  DOBBY_ROOT={DOBBY_ROOT}")
    print("  <checkout-venv>/python -m integration.cli config/dobby_loop.yaml")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__.strip().splitlines()[2].strip())
    raise SystemExit(main(sys.argv[1]))
